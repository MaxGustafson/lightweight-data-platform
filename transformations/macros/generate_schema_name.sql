{# Override dbt's default `{target_schema}_{custom}` suffix behaviour so
   per-folder `+schema:` configs produce literal schema names. #}
{% macro generate_schema_name(custom_schema_name, node) -%}
    {%- if custom_schema_name is none -%}
        {{ target.schema }}
    {%- else -%}
        {{ custom_schema_name | trim }}
    {%- endif -%}
{%- endmacro %}
